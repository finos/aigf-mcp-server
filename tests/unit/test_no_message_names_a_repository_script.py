"""No message the installed server can emit names a path under ``scripts/`` (#331).

After every live listing the server compared it with the built-in catalog and
logged "run: python scripts/update-static-fallback.py". A deployer installs the
package, not the repository: they have no ``scripts/`` directory, and the only
action open to them was an upgrade, which the text did not name.

The guard walks every string constant under ``src/finos_mcp`` that is not a
docstring. A docstring is for a reader of the source, who has the repository;
a log message, an exception text or a tool description reaches a deployer or a
client. What it does not catch: a path assembled at run time, or one written
without the ``scripts/`` prefix.
"""

from __future__ import annotations

import ast
from pathlib import Path

import pytest

import finos_mcp

pytestmark = pytest.mark.unit

_PACKAGE = Path(finos_mcp.__file__).resolve().parent
_NEEDLE = "scripts/"


def _docstring_nodes(tree: ast.AST) -> set[int]:
    """Line numbers of every docstring constant in the tree."""
    lines: set[int] = set()
    for node in ast.walk(tree):
        if not isinstance(
            node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef
        ):
            continue
        body = node.body
        if (
            body
            and isinstance(body[0], ast.Expr)
            and isinstance(body[0].value, ast.Constant)
            and isinstance(body[0].value.value, str)
        ):
            lines.add(body[0].value.lineno)
    return lines


def _offenders(source: str) -> list[tuple[int, str]]:
    tree = ast.parse(source)
    docstrings = _docstring_nodes(tree)
    return [
        (node.lineno, node.value)
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and _NEEDLE in node.value
        and node.lineno not in docstrings
    ]


def test_no_string_the_server_emits_names_a_repository_script() -> None:
    found = {
        str(path.relative_to(_PACKAGE.parent)): offenders
        for path in sorted(_PACKAGE.rglob("*.py"))
        if (offenders := _offenders(path.read_text(encoding="utf-8")))
    }

    assert not found, (
        "a message the installed server can emit names a path a deployer does "
        f"not have:\n{found}"
    )


def test_the_scanner_reads_a_message_and_passes_over_a_docstring() -> None:
    """The guard above passes over an empty selection; this proves it can find one."""
    message = 'logger.warning("run: python scripts/update.py")\n'
    assert _offenders(message) == [(1, "run: python scripts/update.py")]

    docstring = '"""Generated by scripts/update.py; see the guide."""\n'
    assert _offenders(docstring) == []

    method = (
        "class A:\n"
        '    """Class docstring naming scripts/x.py."""\n'
        "    def f(self):\n"
        '        """Method docstring naming scripts/y.py."""\n'
        '        raise ValueError("see scripts/z.py")\n'
    )
    assert _offenders(method) == [(5, "see scripts/z.py")]
