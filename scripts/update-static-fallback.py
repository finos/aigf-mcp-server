#!/usr/bin/env python3
"""Regenerate ``src/finos_mcp/content/static_catalog.py`` from the GitHub API.

That module is the listing the server serves when GitHub cannot be asked and
it holds no list file for the configured base_url. This script lists the three
content directories, refuses any name outside the shape the corpus has, and
writes the module whole. Review the diff and commit it; nothing is copied by
hand.
"""

import asyncio
import json
import re
import sys
from datetime import UTC, datetime
from pathlib import Path

# Add src to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

from tenacity import RetryError

from finos_mcp.config import get_settings
from finos_mcp.content.fetch import get_http_client
from finos_mcp.content.github_api import FRAMEWORKS, MITIGATIONS, RISKS, list_directory

ROOT = Path(__file__).resolve().parent.parent
MODULE = ROOT / "src" / "finos_mcp" / "content" / "static_catalog.py"

#: What a name in each directory looks like, and the variable it is written to.
#: Tighter than the listing's own rule (``github_api._NAME``): these names are
#: written into Python source, and the corpus has never held anything else.
DIRECTORIES = (
    ("mitigations", re.compile(r"mi-\d+_[a-z0-9-]+\.md"), "STATIC_MITIGATION_FILES"),
    ("risks", re.compile(r"ri-\d+_[a-z0-9-]+\.md"), "STATIC_RISK_FILES"),
    ("frameworks", re.compile(r"[a-z0-9-]+\.yml"), "STATIC_FRAMEWORK_FILES"),
)

_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")
_LISTED_ON = re.compile(r'^LISTED_ON = "(\d{4}-\d{2}-\d{2})"$', re.MULTILINE)

_HEADER = '''# Copyright 2025 FINOS
# SPDX-License-Identifier: Apache-2.0

"""The listing built into the server, for when GitHub cannot be asked.

Generated by ``scripts/update-static-fallback.py`` from a listing of the
upstream repository on the date below; do not edit by hand. ``discovery``
serves it with source ``static_fallback`` when it holds no list file for the
configured base_url and the GitHub API cannot be asked, or cannot address that
base_url.
"""
'''


async def fetch_live_listing():
    """List the three content directories straight from the GitHub API.

    Deliberately not ``discover_content()``: that serves the listing a server
    run left under the discovery cache directory for the next hour, and answers
    a failed request with the static lists -- the very lists this script exists
    to replace (#207). Nothing here reads or writes a cache, and a failure
    raises instead of being answered from somewhere else: the transport error
    when GitHub cannot be reached, ``GitHubRateLimitError`` when it throttles,
    ``GitHubDiscoveryError`` for any other answer that is not a listing.

    tests/integration/test_static_fallback_sync.py calls this too, so the script
    and the check that tells you to run it read the same listing.
    """
    settings = get_settings()
    client = await get_http_client()
    listing = {}
    for name, directory in (
        ("mitigations", MITIGATIONS),
        ("risks", RISKS),
        ("frameworks", FRAMEWORKS),
    ):
        try:
            files = await list_directory(
                client, settings.repo_target, directory, settings.github_token
            )
        except RetryError as exc:
            # The HTTP client retries, then raises tenacity's wrapper, whose
            # text is "RetryError[<Future ...>]". Raise what it wraps, so the
            # caller sees the connection error and can tell it from a refusal.
            exc.reraise()
        listing[name] = sorted(f.filename for f in files)
    return listing


def render_module(listing, listed_on):
    """The text of ``static_catalog.py`` for a listing.

    Raises ``ValueError`` for a name outside its directory's shape, or a date
    that is not one. Names are sorted and written through ``json.dumps``, which
    is a valid Python string literal; the output is what ``ruff format``
    leaves alone, and a test holds the shipped module to that.
    """
    if _DATE.fullmatch(listed_on) is None:
        raise ValueError(f"{listed_on!r} is not a date of the form 2026-10-13")
    parts = [_HEADER, f"\nLISTED_ON = {json.dumps(listed_on)}\n"]
    for directory, rule, variable in DIRECTORIES:
        names = sorted(listing[directory])
        for name in names:
            if rule.fullmatch(name) is None:
                raise ValueError(
                    f"{directory}: {name!r} is not a name this directory holds "
                    f"(rule {rule.pattern})"
                )
        entries = "".join(f"    {json.dumps(name)},\n" for name in names)
        parts.append(f"\n{variable} = [\n{entries}]\n")
    return "".join(parts)


async def main():
    """List GitHub, write the module when the lists changed, say what was done."""
    print("Listing the content directories through the GitHub API...")
    try:
        listing = await fetch_live_listing()
    except Exception as exc:
        print(f"\n✗ GitHub API request failed: {type(exc).__name__}: {exc}")
        return 1
    for directory, _rule, _variable in DIRECTORIES:
        print(f"✓ {len(listing[directory])} {directory}")

    current = MODULE.read_text(encoding="utf-8") if MODULE.exists() else ""
    listed_on = _LISTED_ON.search(current)
    try:
        if listed_on and render_module(listing, listed_on.group(1)) == current:
            print(f"\n✓ {MODULE.relative_to(ROOT)} already holds this listing")
            print(f"  (listed on {listed_on.group(1)}); nothing written")
            return 0
        text = render_module(listing, datetime.now(UTC).date().isoformat())
    except ValueError as exc:
        print(f"\n✗ The listing holds a name the catalog cannot carry: {exc}")
        return 1

    MODULE.write_text(text, encoding="utf-8")
    print(f"\n✓ Wrote {MODULE.relative_to(ROOT)}")
    print(f"  Review with: git diff {MODULE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
